--   docker exec lamb-academic-oracle expdp system/<clave>@localhost:1521/FREEPDB1 \
--          schemas=LAMB_APP directory=DATA_PUMP_DIR dumpfile=lamb_app_<fecha>.dmp
--
-- Script ADITIVO: solo CREATE TABLE / CREATE INDEX / ALTER TABLE ... ADD.
-- No modifica ni borra filas existentes de PERIODOS, MATRICULAS ni DETALLE_MATRICULA.
-- Reversion: V2__rollback.sql (requiere autorizacion explicita; elimina solo lo creado aqui).
--
-- Convenciones:
--   * Tablas de Base Universal y Curriculo conservan los nombres de los scripts BD2 del
--     equipo (SEDE, FACULTAD, ESCUELA, CURSO, PERSONA, PLAN_ESTUDIO, DETALLE_PLAN_ESTUDIO).
--   * Relaciones entre modulos hacia registros historicos (matricula, cargos) sin FK fisica
--     (criterio de S4, Tabla 2). Dentro de un modulo y hacia catalogos vivos, con FK.
--   * ALUMNOS y SECCIONES inician su identidad en 1001 para no coincidir con los ids
--     de prueba que ya existen en MATRICULAS (estudiante 1) y DETALLE_MATRICULA (1,2,100,101).
-- =============================================================================

WHENEVER SQLERROR EXIT FAILURE ROLLBACK
SET ECHO ON

-- ------------------------------ BASE UNIVERSAL ------------------------------

CREATE TABLE SEDE (
    ID         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CODIGO     VARCHAR2(20)  NOT NULL,
    NOMBRE     VARCHAR2(150) NOT NULL,
    DIRECCION  VARCHAR2(255),
    ACTIVO     NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT PK_SEDE PRIMARY KEY (ID),
    CONSTRAINT UK_SEDE_CODIGO UNIQUE (CODIGO),
    CONSTRAINT CK_SEDE_ACTIVO CHECK (ACTIVO IN (0, 1))
);

CREATE TABLE FACULTAD (
    ID         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_SEDE    NUMBER NOT NULL,
    CODIGO     VARCHAR2(20)  NOT NULL,
    NOMBRE     VARCHAR2(150) NOT NULL,
    ACTIVO     NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT PK_FACULTAD PRIMARY KEY (ID),
    CONSTRAINT UK_FACULTAD_CODIGO UNIQUE (CODIGO),
    CONSTRAINT FK_FACULTAD_SEDE FOREIGN KEY (ID_SEDE) REFERENCES SEDE (ID),
    CONSTRAINT CK_FACULTAD_ACTIVO CHECK (ACTIVO IN (0, 1))
);

CREATE TABLE ESCUELA (
    ID           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_FACULTAD  NUMBER NOT NULL,
    CODIGO       VARCHAR2(20)  NOT NULL,
    NOMBRE       VARCHAR2(150) NOT NULL,
    NIVEL        VARCHAR2(20) DEFAULT 'PREGRADO' NOT NULL,
    ACTIVO       NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT PK_ESCUELA PRIMARY KEY (ID),
    CONSTRAINT UK_ESCUELA_CODIGO UNIQUE (CODIGO),
    CONSTRAINT FK_ESCUELA_FACULTAD FOREIGN KEY (ID_FACULTAD) REFERENCES FACULTAD (ID),
    CONSTRAINT CK_ESCUELA_NIVEL CHECK (NIVEL IN ('PREGRADO', 'POSGRADO')),
    CONSTRAINT CK_ESCUELA_ACTIVO CHECK (ACTIVO IN (0, 1))
);

CREATE TABLE PERSONA (
    ID                NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TIPO_PERSONA      VARCHAR2(20) NOT NULL,
    TIPO_DOCUMENTO    VARCHAR2(20) NOT NULL,
    NUMERO_DOCUMENTO  VARCHAR2(20) NOT NULL,
    NOMBRES           VARCHAR2(120) NOT NULL,
    APELLIDO_PATERNO  VARCHAR2(80)  NOT NULL,
    APELLIDO_MATERNO  VARCHAR2(80),
    EMAIL             VARCHAR2(150),
    TELEFONO          VARCHAR2(20),
    DIRECCION         VARCHAR2(255),
    FECHA_NACIMIENTO  DATE,
    ID_ESCUELA        NUMBER,
    ACTIVO            NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT PK_PERSONA PRIMARY KEY (ID),
    CONSTRAINT UK_PERSONA_DOC UNIQUE (TIPO_DOCUMENTO, NUMERO_DOCUMENTO),
    CONSTRAINT FK_PERSONA_ESCUELA FOREIGN KEY (ID_ESCUELA) REFERENCES ESCUELA (ID),
    CONSTRAINT CK_PERSONA_TIPO CHECK (TIPO_PERSONA IN ('ALUMNO', 'DOCENTE', 'ADMINISTRATIVO', 'CAJERO', 'EXTERNO')),
    CONSTRAINT CK_PERSONA_TIPO_DOC CHECK (TIPO_DOCUMENTO IN ('DNI', 'CE', 'PASAPORTE', 'RUC')),
    CONSTRAINT CK_PERSONA_ACTIVO CHECK (ACTIVO IN (0, 1))
);

CREATE INDEX IX_PERSONA_APEPAT ON PERSONA (APELLIDO_PATERNO);
CREATE INDEX IX_PERSONA_ESCUELA ON PERSONA (ID_ESCUELA);

CREATE TABLE ALUMNOS (
    ID                 NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1001),
    ID_PERSONA         NUMBER NOT NULL,
    CODIGO_ESTUDIANTE  VARCHAR2(20) NOT NULL,
    ESTADO             VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL,
    FECHA_INGRESO      DATE NOT NULL,
    CONSTRAINT PK_ALUMNOS PRIMARY KEY (ID),
    CONSTRAINT UK_ALUMNOS_PERSONA UNIQUE (ID_PERSONA),
    CONSTRAINT UK_ALUMNOS_CODIGO UNIQUE (CODIGO_ESTUDIANTE),
    CONSTRAINT FK_ALUMNOS_PERSONA FOREIGN KEY (ID_PERSONA) REFERENCES PERSONA (ID),
    CONSTRAINT CK_ALUMNOS_ESTADO CHECK (ESTADO IN ('ACTIVO', 'SUSPENDIDO', 'RETIRADO', 'EGRESADO'))
);

CREATE TABLE EXPEDIENTES (
    ID                NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CODIGO_TRAMITE    VARCHAR2(50)  NOT NULL,
    ASUNTO            VARCHAR2(255) NOT NULL,
    FECHA_REGISTRO    TIMESTAMP NOT NULL,
    ESTADO            VARCHAR2(30) DEFAULT 'REGISTRADO' NOT NULL,
    ID_PERSONA        NUMBER NOT NULL,
    TOTAL_DOCUMENTOS  NUMBER(5) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_EXPEDIENTES PRIMARY KEY (ID),
    CONSTRAINT UK_EXPEDIENTES_CODIGO UNIQUE (CODIGO_TRAMITE),
    CONSTRAINT FK_EXPEDIENTES_PERSONA FOREIGN KEY (ID_PERSONA) REFERENCES PERSONA (ID),
    CONSTRAINT CK_EXPEDIENTES_ESTADO CHECK (ESTADO IN ('REGISTRADO', 'EN_REVISION', 'OBSERVADO', 'APROBADO', 'ARCHIVADO')),
    CONSTRAINT CK_EXPEDIENTES_TOTAL CHECK (TOTAL_DOCUMENTOS >= 0)
);

CREATE INDEX IX_EXPEDIENTES_PERSONA ON EXPEDIENTES (ID_PERSONA);

CREATE TABLE DOCUMENTOS_ADJUNTOS (
    ID              NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_EXPEDIENTE   NUMBER NOT NULL,
    NOMBRE          VARCHAR2(150) NOT NULL,
    NOMBRE_ARCHIVO  VARCHAR2(255) NOT NULL,
    TIPO_DOCUMENTO  VARCHAR2(10)  NOT NULL,
    RUTA_ARCHIVO    VARCHAR2(500) NOT NULL,
    FECHA_CARGA     TIMESTAMP NOT NULL,
    CONSTRAINT PK_DOCUMENTOS_ADJUNTOS PRIMARY KEY (ID),
    CONSTRAINT FK_DOCUMENTOS_EXPEDIENTE FOREIGN KEY (ID_EXPEDIENTE) REFERENCES EXPEDIENTES (ID),
    CONSTRAINT UK_DOCUMENTOS_ARCHIVO UNIQUE (ID_EXPEDIENTE, NOMBRE_ARCHIVO),
    CONSTRAINT CK_DOCUMENTOS_TIPO CHECK (TIPO_DOCUMENTO IN ('PDF', 'JPG', 'PNG', 'DOCX'))
);

-- ------------------------------ CORE ACADEMICO ------------------------------

CREATE TABLE CURSO (
    ID               NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CODIGO           VARCHAR2(20)  NOT NULL,
    NOMBRE           VARCHAR2(150) NOT NULL,
    CREDITOS         NUMBER(2) NOT NULL,
    HORAS_TEORICAS   NUMBER(2) DEFAULT 0 NOT NULL,
    HORAS_PRACTICAS  NUMBER(2) DEFAULT 0 NOT NULL,
    ACTIVO           NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT PK_CURSO PRIMARY KEY (ID),
    CONSTRAINT UK_CURSO_CODIGO UNIQUE (CODIGO),
    CONSTRAINT CK_CURSO_CREDITOS CHECK (CREDITOS BETWEEN 1 AND 10),
    CONSTRAINT CK_CURSO_HORAS CHECK (HORAS_TEORICAS >= 0 AND HORAS_PRACTICAS >= 0),
    CONSTRAINT CK_CURSO_ACTIVO CHECK (ACTIVO IN (0, 1))
);

CREATE TABLE PLAN_ESTUDIO (
    ID              NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_ESCUELA      NUMBER NOT NULL,
    CODIGO          VARCHAR2(30)  NOT NULL,
    NOMBRE          VARCHAR2(150) NOT NULL,
    ANIO            NUMBER(4) NOT NULL,
    VERSION         NUMBER(3) DEFAULT 1 NOT NULL,
    ESTADO          VARCHAR2(20) DEFAULT 'VIGENTE' NOT NULL,
    TOTAL_CREDITOS  NUMBER(4) DEFAULT 0 NOT NULL,
    TOTAL_CURSOS    NUMBER(4) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_PLAN_ESTUDIO PRIMARY KEY (ID),
    CONSTRAINT UK_PLAN_ESTUDIO_CODIGO UNIQUE (CODIGO),
    CONSTRAINT FK_PLAN_ESTUDIO_ESCUELA FOREIGN KEY (ID_ESCUELA) REFERENCES ESCUELA (ID),
    CONSTRAINT CK_PLAN_ESTUDIO_ESTADO CHECK (ESTADO IN ('VIGENTE', 'OBSOLETO'))
);

CREATE INDEX IX_PLAN_ESTUDIO_ESCUELA ON PLAN_ESTUDIO (ID_ESCUELA);

CREATE TABLE DETALLE_PLAN_ESTUDIO (
    ID                NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_PLAN           NUMBER NOT NULL,
    ID_CURSO          NUMBER NOT NULL,
    CICLO             NUMBER(2) NOT NULL,
    CREDITOS          NUMBER(2) NOT NULL,
    TIPO              VARCHAR2(20) DEFAULT 'OBLIGATORIO' NOT NULL,
    ID_PRERREQUISITO  NUMBER,
    CONSTRAINT PK_DETALLE_PLAN_ESTUDIO PRIMARY KEY (ID),
    CONSTRAINT UK_DET_PLAN_CURSO UNIQUE (ID_PLAN, ID_CURSO),
    CONSTRAINT FK_DET_PLAN_PLAN FOREIGN KEY (ID_PLAN) REFERENCES PLAN_ESTUDIO (ID),
    CONSTRAINT FK_DET_PLAN_CURSO FOREIGN KEY (ID_CURSO) REFERENCES CURSO (ID),
    CONSTRAINT FK_DET_PLAN_PRERREQ FOREIGN KEY (ID_PRERREQUISITO) REFERENCES CURSO (ID),
    CONSTRAINT CK_DET_PLAN_CICLO CHECK (CICLO BETWEEN 1 AND 14),
    CONSTRAINT CK_DET_PLAN_CREDITOS CHECK (CREDITOS > 0),
    CONSTRAINT CK_DET_PLAN_TIPO CHECK (TIPO IN ('OBLIGATORIO', 'ELECTIVO')),
    CONSTRAINT CK_DET_PLAN_PRERREQ CHECK (ID_PRERREQUISITO IS NULL OR ID_PRERREQUISITO <> ID_CURSO)
);

CREATE INDEX IX_DETALLE_PLAN ON DETALLE_PLAN_ESTUDIO (ID_PLAN, CICLO);

CREATE TABLE SECCIONES (
