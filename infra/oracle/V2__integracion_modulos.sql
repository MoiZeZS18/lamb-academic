    GRUPO            VARCHAR2(10) NOT NULL,
    ID_DOCENTE       NUMBER,
    LIMITE_VACANTES  NUMBER(4) NOT NULL,
    CUPOS_OCUPADOS   NUMBER(4) DEFAULT 0 NOT NULL,
    ESTADO           VARCHAR2(20) DEFAULT 'ABIERTA' NOT NULL,
    CONSTRAINT PK_SECCIONES PRIMARY KEY (ID),
