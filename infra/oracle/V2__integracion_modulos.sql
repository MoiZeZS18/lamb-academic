    CONSTRAINT FK_SECCIONES_PERIODO FOREIGN KEY (ID_PERIODO) REFERENCES PERIODOS (ID),
    CONSTRAINT FK_SECCIONES_DOCENTE FOREIGN KEY (ID_DOCENTE) REFERENCES PERSONA (ID),
    CONSTRAINT CK_SECCIONES_LIMITE CHECK (LIMITE_VACANTES > 0),
    CONSTRAINT CK_SECCIONES_CUPOS CHECK (CUPOS_OCUPADOS BETWEEN 0 AND LIMITE_VACANTES),
    CONSTRAINT CK_SECCIONES_ESTADO CHECK (ESTADO IN ('ABIERTA', 'CERRADA', 'CANCELADA'))
);

CREATE INDEX IX_SECCIONES_PERIODO ON SECCIONES (ID_PERIODO);
CREATE INDEX IX_SECCIONES_DOCENTE ON SECCIONES (ID_DOCENTE);

CREATE TABLE HORARIOS_AULA (
