-- ID_ESTUDIANTE / ID_PERIODO / ID_REFERENCIA sin FK fisica: el cargo es un documento
-- historico que no debe depender de que el otro registro siga existiendo (S4, Tabla 2).
CREATE TABLE FIN_CARGOS (
    ID               NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NUMERO_CARGO     VARCHAR2(30) NOT NULL,
    ID_ESTUDIANTE    NUMBER NOT NULL,
    PROCESO_ORIGEN   VARCHAR2(30) NOT NULL,
    ID_REFERENCIA    NUMBER,
    ID_PERIODO       NUMBER NOT NULL,
    TOTAL_CREDITOS   NUMBER(3),
    NUMERO_CUOTAS    NUMBER(2) NOT NULL,
    MONTO_TOTAL      NUMBER(12, 2) NOT NULL,
    SALDO_PENDIENTE  NUMBER(12, 2) NOT NULL,
    ESTADO           VARCHAR2(20) DEFAULT 'EMITIDO' NOT NULL,
    OBSERVACION      VARCHAR2(500),
    FECHA_EMISION    TIMESTAMP NOT NULL,
    VERSION          NUMBER(10) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_FIN_CARGOS PRIMARY KEY (ID),
    CONSTRAINT UK_FIN_CARGOS_NUMERO UNIQUE (NUMERO_CARGO),
    CONSTRAINT CK_FIN_CARGOS_ORIGEN CHECK (PROCESO_ORIGEN IN ('MATRICULA', 'TRAMITE', 'OTRO')),
    CONSTRAINT CK_FIN_CARGOS_CUOTAS CHECK (NUMERO_CUOTAS BETWEEN 1 AND 12),
    CONSTRAINT CK_FIN_CARGOS_MONTO CHECK (MONTO_TOTAL >= 0),
    CONSTRAINT CK_FIN_CARGOS_SALDO CHECK (SALDO_PENDIENTE BETWEEN 0 AND MONTO_TOTAL),
    CONSTRAINT CK_FIN_CARGOS_ESTADO CHECK (ESTADO IN ('EMITIDO', 'PAGADO_PARCIAL', 'PAGADO_TOTAL', 'ANULADO'))
);

-- Idempotencia: un solo cargo por (proceso, referencia) cuando la referencia existe.
-- Indice funcional: los cargos sin referencia (ID_REFERENCIA NULL) no participan.
CREATE UNIQUE INDEX UX_FIN_CARGOS_ORIGEN ON FIN_CARGOS (
    CASE WHEN ID_REFERENCIA IS NOT NULL THEN PROCESO_ORIGEN END,
    CASE WHEN ID_REFERENCIA IS NOT NULL THEN ID_REFERENCIA END
);

CREATE INDEX IX_FIN_CARGOS_ESTUDIANTE ON FIN_CARGOS (ID_ESTUDIANTE);

CREATE TABLE FIN_DETALLE_CARGOS (
    ID                 NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_CARGO           NUMBER NOT NULL,
    NUMERO_CUOTA       NUMBER(2) NOT NULL,
    CONCEPTO_NOMBRE    VARCHAR2(150) NOT NULL,
    FECHA_VENCIMIENTO  DATE NOT NULL,
    MONTO_CUOTA        NUMBER(12, 2) NOT NULL,
    MONTO_PAGADO       NUMBER(12, 2) DEFAULT 0 NOT NULL,
    ESTADO             VARCHAR2(20) DEFAULT 'PENDIENTE' NOT NULL,
    CONSTRAINT PK_FIN_DETALLE_CARGOS PRIMARY KEY (ID),
    CONSTRAINT UK_FIN_DETALLE_CUOTA UNIQUE (ID_CARGO, NUMERO_CUOTA),
    CONSTRAINT FK_FIN_DETALLE_CARGO FOREIGN KEY (ID_CARGO) REFERENCES FIN_CARGOS (ID),
    CONSTRAINT CK_FIN_DETALLE_MONTO CHECK (MONTO_CUOTA >= 0),
    CONSTRAINT CK_FIN_DETALLE_PAGADO CHECK (MONTO_PAGADO BETWEEN 0 AND MONTO_CUOTA),
    CONSTRAINT CK_FIN_DETALLE_ESTADO CHECK (ESTADO IN ('PENDIENTE', 'PAGADA_PARCIAL', 'PAGADA', 'ANULADA'))
);

CREATE TABLE FIN_PAGOS (
    ID           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_CARGO     NUMBER NOT NULL,
    MONTO        NUMBER(12, 2) NOT NULL,
    FECHA_PAGO   TIMESTAMP NOT NULL,
    MEDIO_PAGO   VARCHAR2(20) NOT NULL,
    REFERENCIA   VARCHAR2(100),
    CONSTRAINT PK_FIN_PAGOS PRIMARY KEY (ID),
    CONSTRAINT FK_FIN_PAGOS_CARGO FOREIGN KEY (ID_CARGO) REFERENCES FIN_CARGOS (ID),
    CONSTRAINT CK_FIN_PAGOS_MONTO CHECK (MONTO > 0),
    CONSTRAINT CK_FIN_PAGOS_MEDIO CHECK (MEDIO_PAGO IN ('EFECTIVO', 'TARJETA', 'TRANSFERENCIA', 'DEPOSITO'))
);

CREATE INDEX IX_FIN_PAGOS_CARGO ON FIN_PAGOS (ID_CARGO);

